const menuButton = document.querySelector(".menu-toggle");
const siteNav = document.querySelector(".site-nav");
const langButtons = document.querySelectorAll("[data-lang]");

function applyLanguage(lang) {
  const dict = translations[lang] || translations.ro;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (dict[key]) node.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const key = node.getAttribute("data-i18n-aria");
    if (dict[key]) node.setAttribute("aria-label", dict[key]);
  });
  langButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === lang);
    button.setAttribute("aria-pressed", button.dataset.lang === lang ? "true" : "false");
  });
  localStorage.setItem("dataforest-lang", lang);
}

function closeMenu() {
  siteNav.classList.remove("is-open");
  menuButton.setAttribute("aria-expanded", "false");
}

menuButton.addEventListener("click", () => {
  const open = siteNav.classList.toggle("is-open");
  menuButton.setAttribute("aria-expanded", open ? "true" : "false");
});

siteNav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", closeMenu);
});

langButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

document.querySelectorAll(".gallery-item img").forEach((image) => {
  const item = image.parentElement;
  image.addEventListener("load", () => item.classList.remove("is-empty"));
  image.addEventListener("error", () => item.classList.add("is-empty"));
});

const saved = localStorage.getItem("dataforest-lang");
applyLanguage(saved === "en" ? "en" : "ro");
